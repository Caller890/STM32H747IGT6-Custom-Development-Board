  MX_SPI2_Init();
  MX_SPI5_Init();
  MX_USB_DEVICE_Init();
  /* USER CODE BEGIN 2 */
  ConfigurationInit();
  MPU_Config_D2_NonCacheable();
  setup();
  LED_on(&myLED, "blue") ;
  delay(1000);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
	Data_Input();
	loop();
  }
